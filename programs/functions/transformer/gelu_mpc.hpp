template <typename Share>
using AShare = Additive_Share<DATATYPE, Share>;

constexpr int kSegments = 4;
constexpr std::array<FLOATTYPE, kSegments + 1> kEdges = {
    FLOATTYPE(-4), FLOATTYPE(-2), FLOATTYPE(0), FLOATTYPE(2), FLOATTYPE(4)};

// Coefficients are [a3,a2,a1,a0], generated by tools/fit_gelu_poly.py and
// rounded to Q12.20.  The maximum grid error after quantization is 0.004432.
constexpr std::array<std::array<std::int32_t, 4>, kSegments> kCoefficients = {{
    {{-11572, -123823, -442797, -529959}},
    {{109037, 468294, 526061, -1013}},
    {{-109040, 468302, 522510, -1013}},
    {{11572, -123823, 1491373, -529959}},
}};

inline UINT_TYPE fixed(FLOATTYPE value)
{
    return FloatFixedConverter<FLOATTYPE, INT_TYPE, UINT_TYPE, FRACTIONAL>::float_to_ufixed(value);
}

template <typename Share>
void multiply_fixed(const AShare<Share>* lhs,
                    const AShare<Share>* rhs,
                    AShare<Share>* out,
                    int len)
{
    using A = AShare<Share>;
    constexpr int limb_bits = FRACTIONAL / 2;
    constexpr UINT_TYPE limb_base = UINT_TYPE(1) << limb_bits;
    std::vector<A> high_lhs(lhs, lhs + len);
    std::vector<A> high_rhs(rhs, rhs + len);
    trunc_exact_in_place(high_lhs.data(), len, limb_bits);
    trunc_exact_in_place(high_rhs.data(), len, limb_bits);
    std::vector<A> low_lhs(len);
    std::vector<A> low_rhs(len);
    std::vector<A> cross(len);
    for (int i = 0; i < len; ++i)
    {
        low_lhs[i] = lhs[i] - high_lhs[i].mult_public(limb_base);
        low_rhs[i] = rhs[i] - high_rhs[i].mult_public(limb_base);
        out[i] = high_lhs[i].prepare_dot(high_rhs[i]);
        cross[i] = high_lhs[i].prepare_dot(low_rhs[i]) + low_lhs[i].prepare_dot(high_rhs[i]);
        out[i].mask_and_send_dot_without_trunc();
        cross[i].mask_and_send_dot_without_trunc();
    }
    Share::communicate();
    for (int i = 0; i < len; ++i)
    {
        out[i].complete_mult_without_trunc();
        cross[i].complete_mult_without_trunc();
    }
    trunc_exact_in_place(cross.data(), len, limb_bits);
    for (int i = 0; i < len; ++i)
        out[i] = out[i] + cross[i];
}

template <typename Share>
void multiply_bit(const AShare<Share>* bit,
                  const AShare<Share>* value,
                  AShare<Share>* out,
                  int len)
{
    for (int i = 0; i < len; ++i)
    {
        out[i] = bit[i].prepare_dot(value[i]);
        out[i].mask_and_send_dot_without_trunc();
    }
    Share::communicate();
    for (int i = 0; i < len; ++i)
        out[i].complete_mult_without_trunc();
}

// Secure piecewise GELU. Comparisons are batched in one A->B/MSB invocation;
// all four cubics are evaluated with three vectorized Horner multiplications.
template <typename Share>
void gelu_mpc_forward(const AShare<Share>* input, AShare<Share>* output, int len)
{
    using A = AShare<Share>;
    static_assert(BITLENGTH == 32, "MPC GELU requires BITLENGTH=32");
    static_assert(FRACTIONAL == 20, "MPC GELU coefficients require FRACTIONAL=20");
    static_assert(TRUNC_APPROACH == 2, "MPC GELU requires exact truncation");
    if (len < 0)
        throw std::invalid_argument("gelu_mpc_forward length cannot be negative");
    if (len == 0)
        return;

    std::vector<A> comparisons((kSegments + 1) * len);
    std::vector<A> less((kSegments + 1) * len);
    for (int edge = 0; edge <= kSegments; ++edge)
        for (int i = 0; i < len; ++i)
            comparisons[edge * len + i] = input[i] - A(fixed(kEdges[edge]));
    pack_additive<0, BITLENGTH>(comparisons.data(), less.data(),
                                static_cast<int>(less.size()),
                                LTZ<0, BITLENGTH, Share, DATATYPE>);

    std::vector<A> ge(less.size());
    for (std::size_t i = 0; i < less.size(); ++i)
        ge[i] = A(UINT_TYPE(1)) - less[i];

    // Clamp the polynomial operand to [-4,4]. This prevents unused polynomial
    // branches from overflowing when an activation lies far outside the fit.
    std::vector<A> lower_delta(len);
    std::vector<A> lower_selected(len);
    std::vector<A> lower_clipped(len);
    for (int i = 0; i < len; ++i)
        lower_delta[i] = input[i] + A(fixed(FLOATTYPE(4)));
    multiply_bit<Share>(ge.data(), lower_delta.data(), lower_selected.data(), len);
    for (int i = 0; i < len; ++i)
        lower_clipped[i] = A(fixed(FLOATTYPE(-4))) + lower_selected[i];
    std::vector<A> upper_excess(len);
    std::vector<A> upper_selected(len);
    std::vector<A> clamped(len);
    for (int i = 0; i < len; ++i)
        upper_excess[i] = lower_clipped[i] - A(fixed(FLOATTYPE(4)));
    multiply_bit<Share>(ge.data() + kSegments * len, upper_excess.data(), upper_selected.data(), len);
    for (int i = 0; i < len; ++i)
        clamped[i] = lower_clipped[i] - upper_selected[i];

    const int polynomial_elements = kSegments * len;
    std::vector<A> x4(polynomial_elements);
    std::vector<A> polynomial(polynomial_elements);
    std::vector<A> product(polynomial_elements);
    for (int segment = 0; segment < kSegments; ++segment)
        for (int i = 0; i < len; ++i)
        {
            const int index = segment * len + i;
            x4[index] = clamped[i];
            polynomial[index] = A(static_cast<UINT_TYPE>(kCoefficients[segment][0]));
        }
    for (int coefficient = 1; coefficient < 4; ++coefficient)
    {
        multiply_fixed<Share>(polynomial.data(), x4.data(), product.data(), polynomial_elements);
        for (int segment = 0; segment < kSegments; ++segment)
            for (int i = 0; i < len; ++i)
            {
                const int index = segment * len + i;
                polynomial[index] = product[index] +
                    A(static_cast<UINT_TYPE>(kCoefficients[segment][coefficient]));
            }
    }

    // Four interior buckets plus the x>=4 identity branch. Values below -4
    // have no active bucket and therefore map exactly to zero.
    std::vector<A> bucket((kSegments + 1) * len);
    std::vector<A> candidate((kSegments + 1) * len);
    std::vector<A> selected((kSegments + 1) * len);
    for (int segment = 0; segment < kSegments; ++segment)
        for (int i = 0; i < len; ++i)
        {
            const int index = segment * len + i;
            bucket[index] = ge[segment * len + i] - ge[(segment + 1) * len + i];
            candidate[index] = polynomial[index];
        }
    for (int i = 0; i < len; ++i)
    {
        bucket[kSegments * len + i] = ge[kSegments * len + i];
        candidate[kSegments * len + i] = input[i];
    }
    multiply_bit<Share>(bucket.data(), candidate.data(), selected.data(),
                        static_cast<int>(selected.size()));
    for (int i = 0; i < len; ++i)
    {
        output[i] = A(UINT_TYPE(0));
        for (int branch = 0; branch <= kSegments; ++branch)
            output[i] = output[i] + selected[branch * len + i];
    }
}

template <typename Share>
void GELU(const AShare<Share>* begin, const AShare<Share>* end, AShare<Share>* output)
{
    const std::ptrdiff_t length = end - begin;
    if (length > static_cast<std::ptrdiff_t>(std::numeric_limits<int>::max()))
        throw std::overflow_error("GELU input is too large");
    gelu_mpc_forward<Share>(begin, output, static_cast<int>(length));
}
